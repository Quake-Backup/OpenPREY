#!/usr/bin/env python3
"""Write the compact layouts of PREY's multiplayer scoreboard.

PREY's scoreboard (guis/scoreboard.gui) lists eight players in deathmatch and
eight a team in Team DM, as many as retail servers took. openPR06's servers
take 32 (MAX_CLIENTS), so the game (idMultiplayerGame::UpdateDMScoreboard and
UpdateTeamScoreboard) chooses a layout and publishes it:

  sb_layout   0: the stock board, untouched (up to 8 lines, or 8 a team)
              1: one compact column in the stock panel (deathmatch, 9-16 lines)
              2: two compact columns in a wider panel (deathmatch, 17-32
                 lines: the first half leads; Team DM past 8 a team: red
                 leads, blue trails)
  sb_pitch    the compact rows' pitch in units (12-24)
  sb_split    deathmatch: the lines in the leading column
  sb_count    deathmatch: the lines; red_count, blue_count: each team's rows

The stock windows keep drawing layout 0 (and layout 1's frame, headings and
footer). This script writes the compact windows between the markers at the
end of the stock file, in the stock furniture: the slate panel, the black
column wells, the body face at 0.25, Team DM's red and blue heading strips
and the local player's bar (docs/dev/prey-ui-visual-design.md, section 10.6).
Edit this script, not the generated windows; --check reports a stale file.

Expressions are fully parenthesized: the GUI parser reads every binary
operator right-associatively (a - b + c is a - (b + c)), and reads a bare
term after a conditional's ':' as the window's own variable. A conditional's
false branch is always a constant: computed there, it reads 0 (see cond).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GUI = ROOT / "content" / "basepr" / "pak0" / "guis" / "scoreboard.gui"
BEGIN = "\t// openPR06: compact layouts, generated by tools/ui/build_scoreboard.py; edit the generator, not these windows\n"
END = "\t// openPR06: end of the generated compact layouts\n"

# The stock windows that yield to the compact layouts; each must be present.
STOCK_GATES = (
    ("windowDef Scoreboard_Common {\n\t\trect\t\t50, 70, 640, 480\n",
     "windowDef Scoreboard_Common {\n\t\trect\t\t50, 70, 640, 480\n\t\tvisible\t\t( \"gui::sb_layout\" != 2 )\t// openPR06: layout 2 has its own frame\n"),
    ("\t\twindowDef WholeBackground {\n\t\t\trect\t\t25, 20, 477, 355\n\t\t\tbackcolor \t0.2, 0.3, 0.4, 0.6\n",
     "\t\twindowDef WholeBackground {\n\t\t\trect\t\t25, 20, 477, 355\n"
     "\t\t\tbackcolor \t0.2, 0.3, 0.4, ( ( \"gui::sb_layout\" != 0 ) ? 0.8 : 0.6 )\t// openPR06: denser behind compact rows\n"),
    ("\twindowDef NoTeams {\n\t\trect\t\t50, 70, 640, 480\n\t\tvisible\t\t(\"gui::teamdm\" == 0)\n",
     "\twindowDef NoTeams {\n\t\trect\t\t50, 70, 640, 480\n\t\tvisible\t\t( ( \"gui::teamdm\" == 0 ) && ( \"gui::sb_layout\" == 0 ) )\t// openPR06\n"),
    ("\twindowDef TeamScoreboard {\n\t\trect\t\t50, 70, 640, 480\n\t\tvisible\t\t\"gui::teamdm\"\n",
     "\twindowDef TeamScoreboard {\n\t\trect\t\t50, 70, 640, 480\n\t\tvisible\t\t( ( \"gui::teamdm\" != 0 ) && ( \"gui::sb_layout\" == 0 ) )\t// openPR06\n"),
)

# Furniture, from the stock windows.
PANEL = "0.2, 0.3, 0.4, 0.8"            # WholeBackground, denser behind compact rows (section 12.3, rule 5)
RIM = "0.7, 0.8, 0.9, 0.9"              # the panel's 1 u border, the headings' and footer's text
WELL = "0, 0, 0, 0.35"                  # the column wells, with a black 1 u border
SELF_FILL = "0.7, 0.8, 0.9, 0.2"        # BarSelf
FOOT_FILL = "0.7, 0.8, 0.9, 0.1"        # GameType's bar
TEAM_FILL = {"red": "0.75, 0, 0, 1", "blue": "0, 0, 0.65, 1"}
TEAM_TITLE = {"red": "#str_20653", "blue": "#str_20654"}   # Team Red, Team Blue
HEADINGS = ("#str_20128", "#str_20651", "#str_20652", "#str_20174")   # Name, Frags, Wins, Ping

ROW_H = 13                              # a compact row: the stock team rows' 13 u row and portrait
LIST_TOP = 119                          # the compact list's first band, 2 u into the wells (117)
TEAM_TOP = 136                          # under a team's 15 u heading strip at 119
DM_ROWS = 32                            # MAX_CLIENTS
TEAM_ROWS = 22                          # SB_TEAM_ROWS: 269 u at the 12 u floor

# Layout 1: the stock wells (Scoreboard_Common at 50,70): Name 82..267,
# Frags 269, Wins 361, Ping 453, 91 u each; the row's cells relative to 82.
STOCK_X = 82
STOCK_CELLS = ((22, 163), (187, 91), (279, 91), (371, 91))
STOCK_BAR = (84, 458)
# Layout 2: two 300 u blocks in a 620 u panel at 10,90; the cells relative
# to the block: Name 0..128, Frags 130..192, Wins 194..242, Ping 244..299.
WIDE_PANEL = (10, 90, 620, 355)
BLOCK_X = (17, 323)
BLOCK_STEP = BLOCK_X[1] - BLOCK_X[0]
BLOCK_W = 300
WIDE_WELLS = ((0, 129), (130, 63), (194, 49), (244, 56))
WIDE_CELLS = ((20, 107), (130, 63), (194, 49), (244, 56))
WIDE_BAR = (2, 296)

LAYOUT = '"gui::sb_layout"'
PITCH = '"gui::sb_pitch"'
SPLIT = '"gui::sb_split"'
SELF = '"gui::rank_self"'


def op(a, sign: str, b) -> str:
    return f"( {a} {sign} {b} )"


def constant(value) -> bool:
    try:
        float(str(value))
        return True
    except ValueError:
        return False


def cond(test: str, yes, no) -> str:
    # The false branch must be a constant: the conditional's op is emitted
    # before the false branch's ops, which therefore run after it, so a
    # computed false branch reads 0 (idWindow::EvaluateRegisters). A computed
    # branch goes first, under the inverted test. Both branches stand in
    # parentheses: the parser reads a bare term after ':' as the window's
    # own variable, so ( a ? 17 : "gui::x" ) would rebind the rect to gui::x.
    if not constant(no):
        if not constant(yes):
            raise SystemExit(f"a GUI conditional needs a constant branch: {test} ? {yes} : {no}")
        test, yes, no = f"( {test} == 0 )", no, yes
    return f"( {test} ? ( {yes} ) : ( {no} ) )"


def num(value: float) -> str:
    return f"{value:g}"


BAR_H = cond(op(PITCH, ">", 17), 17, PITCH)
WIDE = op(LAYOUT, "==", 2)


def box(name: str, rect, fill: str, border: str, indent: int) -> list[str]:
    t = "\t" * indent
    return [f"{t}windowDef {name} {{", f"{t}\trect\t\t{', '.join(num(v) for v in rect)}", f"{t}\tbackcolor\t{fill}",
            f"{t}\tbordercolor\t{border}", f"{t}\tbordersize\t1", f"{t}}}"]


def caption(name: str, rect, text: str, indent: int, *, scale: float = 0.3, align: int = 1, aligny: int = -3,
            colour: str = RIM, shadow: bool = True) -> list[str]:
    t = "\t" * indent
    lines = [f"{t}windowDef {name} {{", f"{t}\trect\t\t{', '.join(num(v) if not isinstance(v, str) else v for v in rect)}",
             f"{t}\ttext\t\t\"{text}\""]
    if shadow:
        lines.append(f"{t}\tshadow\t\t1")
    lines += [f"{t}\ttextscale\t{num(scale)}", f"{t}\ttextalign\t{align}", f"{t}\ttextaligny\t{aligny}",
              f"{t}\tforecolor\t{colour}", f"{t}}}"]
    return lines


def wide_frame() -> list[str]:
    """Layout 2's panel: two blocks of headings and wells, and the footer."""
    out = ["\twindowDef Compact_Wide {", "\t\trect\t\t0, 0, 640, 480", f"\t\tvisible\t\t{WIDE}", ""]
    out += box("Wide_Background", WIDE_PANEL, PANEL, RIM, 2)
    for block, x0 in enumerate(BLOCK_X):
        for column, ((x, w), key) in enumerate(zip(WIDE_WELLS, HEADINGS)):
            out += box(f"Wide_Head{block}_{column}", (x0 + x, 97, w, 19), WELL, "0, 0, 0, 1", 2)
            if column == 0:
                out += caption(f"Wide_HeadText{block}_{column}", (x0 + x + 18, 97, w - 18, 19), key, 2, align=0)
            else:
                out += caption(f"Wide_HeadText{block}_{column}", (x0 + x, 97, w, 19), key, 2)
            out += box(f"Wide_Well{block}_{column}", (x0 + x, 117, w, 290), WELL, "0, 0, 0, 1", 2)
    left, width = BLOCK_X[0], BLOCK_X[1] + BLOCK_W - BLOCK_X[0]
    out += caption("Wide_LivesInfo", (left + 3, 406, width - 6, 35), "gui::livesinfo", 2, align=0, aligny=6)
    out += ["\t\twindowDef Wide_GameType {", f"\t\t\trect\t\t{left}, 410, {width}, 28", "\t\t\ttext\t\t\"gui::gameinfo\"",
            "\t\t\tshadow\t\t1", "\t\t\ttextscale\t0.4", "\t\t\ttextalign\t1", "\t\t\ttextaligny\t-3",
            f"\t\t\tbackcolor\t{FOOT_FILL}", f"\t\t\tforecolor\t{RIM}", f"\t\t\tbordercolor\t{RIM}", "\t\t\tbordersize\t1", "\t\t}"]
    out += caption("Wide_TimeInfo", (left + 3, 406, width - 6, 35), "gui::timeinfo", 2, align=2, aligny=6)
    out.append("\t}")
    return out


def row(name: str, prefix: str, rect, cells, alpha: str, visible: str, portrait_alpha: str = "1") -> list[str]:
    """A compact row: portrait, name, frags, wins and ping on one 13 u line."""
    t = "\t\t"
    out = [f"{t}windowDef {name} {{", f"{t}\trect\t\t{', '.join(str(v) for v in rect)}", f"{t}\tvisible\t\t{visible}", "",
           f"{t}\twindowDef {name}_portrait {{", f"{t}\t\trect\t\t3, 0, {ROW_H}, {ROW_H}",
           f"{t}\t\tbackground\t\"gui::{prefix}_portrait\"", f"{t}\t\tmatcolor\t1, 1, 1, {portrait_alpha}", f"{t}\t}}"]
    for (x, w), (field, align) in zip(cells, ((prefix, 0), (f"{prefix}_score", 1), (f"{prefix}_wins", 1), (f"{prefix}_ping", 1))):
        out += [f"{t}\twindowDef {name}_{field.split('_')[-1] if '_' in field else 'name'} {{",
                f"{t}\t\trect\t\t{x}, 0, {w}, {ROW_H}", f"{t}\t\ttext\t\t\"gui::{field}\"", f"{t}\t\tshadow\t\t1",
                f"{t}\t\tnowrap\t\t1", f"{t}\t\ttextalign\t{align}", f"{t}\t\ttextaligny\t-3",
                f"{t}\t\tforecolor\t1, 1, 1, {alpha}", f"{t}\t\ttextscale\t0.25", f"{t}\t}}"]
    out.append(f"{t}}}")
    return out


def by_layout(stock, wide) -> str:
    return cond(WIDE, wide, stock)


def dm_list() -> list[str]:
    """Deathmatch rows for layouts 1 and 2: the first sb_split lines lead."""
    out = ["\twindowDef Compact_List {", "\t\trect\t\t0, 0, 640, 480",
           f"\t\tvisible\t\t( ( \"gui::teamdm\" == 0 ) && ( {LAYOUT} != 0 ) )", ""]
    trails = op(SELF, ">", SPLIT)
    bar_x = by_layout(STOCK_BAR[0], op(BLOCK_X[0] + WIDE_BAR[0], "+", op(BLOCK_STEP, "*", trails)))
    bar_line = op(op(SELF, "-", 1), "-", op(trails, "*", SPLIT))
    bar_y = op(LIST_TOP, "+", op(op(bar_line, "*", PITCH), "+", op(op(PITCH, "-", BAR_H), "/", 2)))
    out += ["\t\twindowDef Compact_BarSelf {", f"\t\t\trect\t\t{bar_x}, {bar_y}, {by_layout(STOCK_BAR[1], WIDE_BAR[1])}, {BAR_H}",
            f"\t\t\tbordercolor\t{RIM}", f"\t\t\tbackcolor\t{SELF_FILL}", "\t\t\tbordersize\t1", f"\t\t\tvisible\t\t( {SELF} != 0 )",
            "\t\t}", ""]
    cells = [(by_layout(sx, wx), by_layout(sw, ww)) for (sx, sw), (wx, ww) in zip(STOCK_CELLS, WIDE_CELLS)]
    for index in range(1, DM_ROWS + 1):
        trails = op(index, ">", SPLIT)
        line = op(index - 1, "-", op(trails, "*", SPLIT))
        x = by_layout(STOCK_X, op(BLOCK_X[0], "+", op(BLOCK_STEP, "*", trails)))
        y = op(LIST_TOP, "+", op(op(line, "*", PITCH), "+", op(op(PITCH, "-", ROW_H), "/", 2)))
        width = by_layout(STOCK_BAR[1], BLOCK_W)
        # Spectators and connecting players (rank 0) are listed, dimmed; the stock hid them.
        ranked = op(f'"gui::rank{index}"', "!=", 0)
        out += row(f"Compact_Player{index}", f"player{index}", (x, y, width, ROW_H), cells, cond(ranked, 0.8, 0.45),
                   op(index, "<=", '"gui::sb_count"'), cond(ranked, 1, 0.45))
    out.append("\t}")
    return out


def team_lists() -> list[str]:
    """Team DM in layout 2: red leads, blue trails, each under its strip."""
    out = ["\twindowDef Compact_Teams {", "\t\trect\t\t0, 0, 640, 480",
           f"\t\tvisible\t\t( ( \"gui::teamdm\" != 0 ) && {WIDE} )", ""]
    for team, x0 in zip(("red", "blue"), BLOCK_X):
        title = team.capitalize()
        out += [f"\t\twindowDef Compact_Heading{title} {{", f"\t\t\trect\t\t{x0 + 2}, 119, {BLOCK_W - 4}, 15",
                f"\t\t\tbackcolor\t{TEAM_FILL[team]}", "\t\t\tforecolor\t1, 1, 1, 1", f"\t\t\ttext\t\t\"{TEAM_TITLE[team]}\"",
                "\t\t\ttextscale\t0.3", "\t\t\ttextalign\t0", "\t\t\ttextaligny\t-5", "",
                f"\t\t\twindowDef Compact_{title}Score {{", f"\t\t\t\trect\t\t0, 0, {round((BLOCK_W - 4) * 425 / 458)}, 15",
                f"\t\t\t\ttext\t\t\"gui::{team}_score\"", "\t\t\t\ttextscale\t0.3", "\t\t\t\ttextalign\t1", "\t\t\t\ttextaligny\t-5",
                "\t\t\t}", "\t\t}", ""]
        bar_y = op(TEAM_TOP, "+", op(op(op(SELF, "-", 1), "*", PITCH), "+", op(op(PITCH, "-", BAR_H), "/", 2)))
        out += [f"\t\twindowDef Compact_{title}BarSelf {{", f"\t\t\trect\t\t{x0 + WIDE_BAR[0]}, {bar_y}, {WIDE_BAR[1]}, {BAR_H}",
                f"\t\t\tbordercolor\t{RIM}", f"\t\t\tbackcolor\t{SELF_FILL}", "\t\t\tbordersize\t1",
                f"\t\t\tvisible\t\t( ( \"gui::local_team_{team}\" != 0 ) && ( {SELF} != 0 ) )", "\t\t}", ""]
        for index in range(1, TEAM_ROWS + 1):
            y = op(TEAM_TOP, "+", op(op(index - 1, "*", PITCH), "+", op(op(PITCH, "-", ROW_H), "/", 2)))
            out += row(f"Compact_{title}{index}", f"{team}{index}", (x0, y, BLOCK_W, ROW_H), WIDE_CELLS, "0.8",
                       op(index, "<=", f'"gui::{team}_count"'))
    out.append("\t}")
    return out


def generated() -> str:
    body = ["", *wide_frame(), "", *dm_list(), "", *team_lists(), ""]
    return BEGIN + "\n".join(body) + "\n" + END


def render(current: str) -> str:
    text = current
    for stock, gated in STOCK_GATES:
        if gated in text:
            continue
        if stock not in text:
            raise SystemExit(f"scoreboard.gui: the stock window to gate is missing: {stock.splitlines()[0].strip()}")
        text = text.replace(stock, gated, 1)
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        if END not in rest:
            raise SystemExit("scoreboard.gui: the generated block has no end marker")
        tail = rest.split(END, 1)[1]
        return head + generated() + tail
    # First run: the block goes inside Desktop, before its closing brace.
    closing = text.rstrip().rfind("}")
    return text[:closing] + generated() + text[closing:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report a stale scoreboard.gui instead of writing it")
    args = parser.parse_args()
    current = GUI.read_bytes().decode("utf-8").replace("\r\n", "\n")
    rendered = render(current)
    if rendered == current:
        return 0
    if args.check:
        print("stale guis/scoreboard.gui; run tools/ui/build_scoreboard.py")
        return 1
    GUI.write_bytes(rendered.encode("utf-8"))
    print(f"wrote {GUI.relative_to(ROOT).as_posix()} ({len(rendered) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
